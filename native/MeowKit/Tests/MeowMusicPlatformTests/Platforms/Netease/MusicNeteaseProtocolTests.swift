    func testAESDecryptAcceptsFixedValidPaddingInECBAndCBC() throws {
        // Independently calculated with .NET AES/no-padding over explicitly
        // padded synthetic bytes, never generated by MusicNeteaseCrypto.
        let vectors: [(plain: Data, ecb: String, cbc: String)] = [
            (Data(), "aqOxAvvnKWqw256lxGrRKw==", "R+2y/493Fh5e7KhyLuk5zA=="),
            (Data("synthetic".utf8), "nDAtcu3LA4kVpwGJSQuzgw==", "xcFKRGs2ZSBIlLcI+QIgHA=="),
            (Data("0123456789abcdef".utf8), "Eq2ZxHbzB7mvpCaG2I+nT2qjsQL75ylqsNuepcRq0Ss=",
             "tJzM324VrigtySeyLqdTCIyQhG1D2zyfigW4W7/7XE8=")
        ]
        for vector in vectors {
            let modes: [(iv: Data?, ciphertext: String)] = [
                (nil, vector.ecb), (Data("0102030405060708".utf8), vector.cbc)
            ]
            for mode in modes {
                let encrypted = try XCTUnwrap(Data(base64Encoded: mode.ciphertext))
                XCTAssertEqual(try MusicNeteaseCrypto.aes(vector.plain, key: MusicNeteaseCrypto.eapiKey, iv: mode.iv), encrypted)
                XCTAssertEqual(try MusicNeteaseCrypto.aes(encrypted, key: MusicNeteaseCrypto.eapiKey, iv: mode.iv, decrypt: true), vector.plain)
            }
        }
    }
    func testAESDecryptRejectsIncompleteBlocksAndEveryInvalidPaddingForm() throws {
        // Raw padded blocks: all 0; all 17; 14 zeros + [3,2];
        // [15] + fifteen 16s. The last two require checking the entire suffix.
        let vectors: [(name: String, ecb: String, cbc: String)] = [
            ("zero padding", "CkxDe2y6GLX6q3tUVB3MWg==", "setmMwoklX0FaUv+DRu/lw=="),
            ("oversized padding", "BK+u/eo6ubcSKJsnT6mW5A==", "bpB03ESjQdhL6vVrPMl3jA=="),
            ("inconsistent suffix", "ZW1y8lrlpR85IKm1Tsz3kA==", "S0tKKJ0J8fwqQNyzmM/dLw=="),
            ("inconsistent full block", "qkIOF2CwpVUkeAIFRlB9cQ==", "OSK2vx3jZjbfzjmdv1PhLA==")
        ]
        let modes: [Data?] = [nil, Data("0102030405060708".utf8)]
        for iv in modes {
            for length in [0, 1, 15, 17, 31] {
                XCTAssertThrowsError(try MusicNeteaseCrypto.aes(Data(repeating: 0, count: length),
                    key: MusicNeteaseCrypto.eapiKey, iv: iv, decrypt: true), "ciphertext length \(length)") {
                    XCTAssertEqual($0 as? MusicServiceError, .upstreamInvalid)
                }
            }
            for vector in vectors {
                let encrypted = try XCTUnwrap(Data(base64Encoded: iv == nil ? vector.ecb : vector.cbc))
                XCTAssertThrowsError(try MusicNeteaseCrypto.aes(encrypted, key: MusicNeteaseCrypto.eapiKey,
                    iv: iv, decrypt: true), vector.name) {
                    XCTAssertEqual($0 as? MusicServiceError, .upstreamInvalid)
                }
            }
        }
    }
    func testXEAPIIndependentPeerDecodesPayloadAndSessionReuse() throws {
        let peer = try Curve25519.KeyAgreement.PrivateKey(rawRepresentation: Data(repeating: 7, count: 32))
        for count in [16, 24, 32] {
            var state = MusicNeteaseKeyState(publicKey: peer.publicKey.rawRepresentation, sk: "synthetic-sk", version: "1")
            state.sessionID = "synthetic-session"; state.sessionKey = Data(repeating: 65, count: count)
            let form = try MusicNeteaseCrypto.xeapi("/api/song/enhance/player/url/v1",
                data: ["ids": "[101]", "level": "sky", "immerseType": "c51", "encodeType": "flac", "e_r": false], state: state)
            let payload = try MusicNeteaseFixture.xeapi(form, peer: peer)
            XCTAssertEqual(payload, ["ids": "[101]", "level": "sky", "immerseType": "c51", "encodeType": "flac"])
            XCTAssertEqual(try MusicNeteaseFixture.xeapiDynamicKey(form, peer: peer), state.sessionKey)
            let r = try MusicNeteaseFixture.aes(MusicNeteaseFixture.base64(form["R"]!), key: MusicNeteaseFixture.staticKey)
            XCTAssertEqual(String(decoding: r, as: UTF8.self), "1|synthetic-session")
        }
    }
    func testOfficialSessionHeadersAreReusedAndRevocationRequiresFreshHandshake() async throws {
        for count in [16, 24, 32] {
            let clock = MusicAccountTestClock(), key = String(repeating: "A", count: count)
            let http = MusicNeteaseTestHTTP(clock: clock)
            let path = "/xeapi/song/enhance/player/url/v1"
            await http.replies(path, [try MusicNeteaseFixture.response(MusicNeteaseFixture.audio(level: "standard"),
                headers: ["x-encr-ssid": "synthetic-reuse", "x-encr-sskey": key])])
            let adapter = NeteaseMusicAccountAdapter(transport: http, now: { clock.now() })
            _ = try await adapter.publicStandardAudio(nativeID: "101")
            _ = try await adapter.publicStandardAudio(nativeID: "101")
            var calls = await http.recorded()
            XCTAssertEqual(calls.map(\.request.url.path), ["/api/bsr/sk/get", path, path])
            let form = try MusicNeteaseFixture.form(calls[2].request.body)
            let peer = try Curve25519.KeyAgreement.PrivateKey(rawRepresentation: Data(repeating: 7, count: 32))
            XCTAssertEqual(try MusicNeteaseFixture.xeapiDynamicKey(form, peer: peer), Data(key.utf8))
            let r = try MusicNeteaseFixture.aes(MusicNeteaseFixture.base64(form["R"]!), key: MusicNeteaseFixture.staticKey)
            XCTAssertEqual(String(decoding: r, as: UTF8.self), "1|synthetic-reuse")
            await adapter.revoke()
            _ = try await adapter.publicStandardAudio(nativeID: "101")
            calls = await http.recorded()
            XCTAssertEqual(calls.map(\.request.url.path), ["/api/bsr/sk/get", path, path, "/api/bsr/sk/get", path])
            XCTAssertTrue(calls.allSatisfy { !($0.request.headers["Cookie"] ?? "").contains("MUSIC_U") })
        }
    }
