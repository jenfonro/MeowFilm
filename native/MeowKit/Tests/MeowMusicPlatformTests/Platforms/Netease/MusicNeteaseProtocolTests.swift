        }
    }

    func testAllAccountProtocolsRejectCRLFAndNULBeforeNetworking() async throws {
        let transport = URLSessionMusicAccountTransport()
        // No real upstream task can start even if the header guard regresses:
        // a valid request on this transport reports closed, not invalidRequest.
        transport.close()
        for url in ["https://u.y.qq.com/cgi-bin/musicu.fcg", "https://music.163.com/weapi/w/nuser/account/get",
                    "https://interfacepc.music.163.com/eapi/login/qrcode/unikey",
                    "https://interface3.music.163.com/xeapi/register/anonimous"] {
            do {
                _ = try await transport.send(.init(url: URL(string: url)!, headers: ["X-Synthetic": "safe"]))
                XCTFail("Closed transport accepted a request")
            } catch { XCTAssertEqual(error as? MusicServiceError, .closed) }
            for bad in ["one\r\ntwo", "one\rtwo", "one\ntwo", "one\0two"] {
                for headers in [["X-Synthetic": bad], [bad: "synthetic"]] {
                    do {
                        _ = try await transport.send(.init(url: URL(string: url)!, headers: headers))
                        XCTFail("Unsafe header reached URLSession")
                    } catch { XCTAssertEqual(error as? MusicServiceError, .invalidRequest) }
                }
            }
        }
    }
