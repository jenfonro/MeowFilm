import Foundation
import XCTest
import MeowContracts
@testable import MeowPlayback

final class PlaybackListeningFactTests: XCTestCase {
    private func ready() throws -> (PlaybackStateMachine, UUID) {
        var state = PlaybackStateMachine()
        let token = state.begin(resource: try .init(id: "listening",
            url: URL(string: "https://media.invalid/not-requested")!, title: "Synthetic"), owner: "music")
        state.ready(generation: token, duration: 180, ranges: [])
        _ = state.takeEvents()
        return (state, token)
    }
    func testOnlyRealTransportStartsAndBufferProducesNonRunningBoundary() throws {
        var (state, token) = try ready()
        state.transport(generation: token, state: .waiting)
        XCTAssertFalse(state.takeEvents().contains { $0.kind == .played })
        state.transport(generation: token, state: .playing, rate: 2)
        let start = try XCTUnwrap(state.takeEvents().first)
        XCTAssertEqual(start.kind, .played); XCTAssertEqual(start.rate, 2)
        XCTAssertTrue(start.wantsPlayback)
        state.progress(generation: token, position: 4)
        _ = state.takeEvents()
        state.stalled(generation: token)
        let buffer = try XCTUnwrap(state.takeEvents().first)
        XCTAssertEqual(buffer.kind, .progress); XCTAssertEqual(buffer.snapshot.phase, .buffering)
        XCTAssertEqual(buffer.snapshot.position, 4); XCTAssertEqual(buffer.rate, 2)
        XCTAssertTrue(buffer.wantsPlayback)
        XCTAssertFalse(buffer.discontinuity)
        XCTAssertGreaterThanOrEqual(buffer.observedAt, start.observedAt)
        state.transport(generation: token, state: .playing, rate: 2)
        XCTAssertEqual(state.takeEvents().map(\.kind), [.played])
    }
    func testUnchangedWaitingAndSeekSamplesKeepIntentRateAndDiscontinuity() throws {
        var (state, token) = try ready()
        state.transport(generation: token, state: .playing, rate: 2)
        state.progress(generation: token, position: 4)
        _ = state.takeEvents()
        state.transport(generation: token, state: .waiting)
        let waiting = state.takeEvents()
        XCTAssertEqual(waiting.map(\.kind), [.progress])
        let buffer = try XCTUnwrap(waiting.first)
        XCTAssertEqual(buffer.snapshot.phase, .buffering)
        XCTAssertEqual(buffer.snapshot.position, 4)
        XCTAssertEqual(buffer.rate, 2)
        XCTAssertTrue(buffer.wantsPlayback)
        XCTAssertFalse(buffer.discontinuity)
        state.transport(generation: token, state: .waiting)
        state.progress(generation: token, position: 4)
        XCTAssertTrue(state.takeEvents().isEmpty)

        state.rateChanged(generation: token, rate: 1.5, position: 4)
        XCTAssertTrue(state.requestSeek(to: 4))
        let seek = try XCTUnwrap(state.takeSeekIfPossible())
        state.completeSeek(seek, finished: true, actualPosition: 4)
        let boundaries = state.takeEvents()
        XCTAssertEqual(boundaries.map(\.kind), [.progress, .progress])
        XCTAssertTrue(boundaries.allSatisfy {
            $0.wantsPlayback && $0.discontinuity && $0.rate == 1.5
                && $0.snapshot.phase == .buffering && $0.snapshot.position == 4
        })
        XCTAssertTrue(state.shouldPlay)
        state.transport(generation: token, state: .playing, rate: 1.5)
        XCTAssertEqual(state.takeEvents().map(\.kind), [.played])
    }
    func testInterruptionAndUserPauseKeepDistinctIntentWithMeasuredFacts() throws {
        var (state, token) = try ready()
        state.transport(generation: token, state: .playing, rate: 2)
        state.progress(generation: token, position: 4)
        _ = state.takeEvents()
        state.interruptionBegan()
        let interruption = try XCTUnwrap(state.takeEvents().first)
        XCTAssertEqual(interruption.kind, .paused)
        XCTAssertEqual(interruption.snapshot.phase, .paused)
        XCTAssertTrue(interruption.wantsPlayback)
        XCTAssertEqual(interruption.rate, 2)
        XCTAssertEqual(interruption.snapshot.position, 4)

        state.interruptionEnded(shouldResume: true)
        state.transport(generation: token, state: .playing, rate: 2)
        _ = state.takeEvents()
        state.pause()
        let pause = try XCTUnwrap(state.takeEvents().first)
        XCTAssertEqual(pause.kind, .paused)
        XCTAssertFalse(pause.wantsPlayback)
        XCTAssertEqual(pause.rate, 2)
        XCTAssertEqual(pause.snapshot.position, 4)
        XCTAssertGreaterThanOrEqual(pause.observedAt, interruption.observedAt)
        XCTAssertTrue(interruption.wantsPlayback, "Later user intent cannot rewrite an interruption fact")
    }
    func testVideoHandoffFreezesMusicIntentAndFactsBeforeResettingNewAttempt() throws {
        var (state, token) = try ready()
        state.transport(generation: token, state: .playing, rate: 2)
        state.progress(generation: token, position: 4)
        _ = state.takeEvents()
        let video = state.beginVideo(resourceID: "episode", title: "Synthetic", owner: "film", autoplay: false)
        let handoff = state.takeEvents()
        XCTAssertEqual(handoff.map(\.kind), [.replaced, .preparing])
        let exit = try XCTUnwrap(handoff.first), preparation = try XCTUnwrap(handoff.last)
        XCTAssertEqual(exit.attempt.id, token)
        XCTAssertEqual(exit.snapshot.position, 4)
        XCTAssertEqual(exit.rate, 2)
        XCTAssertTrue(exit.wantsPlayback)
        XCTAssertEqual(preparation.attempt.id, video)
        XCTAssertEqual(preparation.snapshot.position, 0)
        XCTAssertEqual(preparation.rate, 1)
        XCTAssertFalse(preparation.wantsPlayback)
        XCTAssertGreaterThan(exit.occurredAt, 0)
        XCTAssertGreaterThanOrEqual(preparation.observedAt, exit.observedAt)

        state.progress(generation: token, position: 8)
        state.rateChanged(generation: token, rate: 3, position: 8)
        state.transport(generation: token, state: .playing, rate: 3)
        XCTAssertTrue(state.takeEvents().isEmpty)
        state.ready(generation: video, duration: 10, ranges: [])
        _ = state.takeEvents()
        XCTAssertTrue(state.resume())
        state.transport(generation: video, state: .playing, rate: 1.5)
        let played = try XCTUnwrap(state.takeEvents().last)
        XCTAssertEqual(played.kind, .played)
        XCTAssertEqual(played.attempt.id, video)
        XCTAssertEqual(played.rate, 1.5)
        XCTAssertTrue(played.wantsPlayback)
        XCTAssertEqual(exit.rate, 2, "The new owner's actual rate cannot rewrite the donor's final sample")
    }
    func testRateAndSmallExternalSeekAreDiscontinuitiesNotNewStarts() throws {
        var (state, token) = try ready()
        state.transport(generation: token, state: .playing)
        state.progress(generation: token, position: 4)
        _ = state.takeEvents()
        state.rateChanged(generation: token, rate: 2, position: 4)
        state.timeJumped(generation: token, position: 4.1)
        let boundaries = state.takeEvents()
        XCTAssertEqual(boundaries.map(\.kind), [.progress, .progress])
        XCTAssertTrue(boundaries.allSatisfy(\.discontinuity))
        XCTAssertTrue(boundaries.allSatisfy { $0.rate == 2 })
        XCTAssertEqual(boundaries.last?.snapshot.position, 4.1)
        XCTAssertTrue(state.requestSeek(to: 4.2))
        XCTAssertTrue(try XCTUnwrap(state.takeEvents().first).discontinuity)
    }
    func testNaturalEndEventKeepsActualPositionWhileUISnapshotSettlesAtDuration() throws {
        var (state, token) = try ready()
        state.transport(generation: token, state: .playing)
        state.progress(generation: token, position: 179.7)
        _ = state.takeEvents()
        XCTAssertTrue(state.end(generation: token))
        let end = try XCTUnwrap(state.takeEvents().first)
        XCTAssertEqual(end.kind, .ended)
        XCTAssertEqual(end.snapshot.position, 179.7)
        XCTAssertFalse(end.wantsPlayback)
        XCTAssertEqual(state.snapshot.position, 180)
        XCTAssertGreaterThan(end.observedAt, 0); XCTAssertGreaterThan(end.occurredAt, 0)
    }
}
