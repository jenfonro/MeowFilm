        case .cat: return "cat.script.v2"
        case .source: return "source.runtime.v2"
        case .pan: return "pan.runtime.v1"
        case .tmdb: return "tmdb.data.v1"
        case .douban: return "douban.data.v1"
        case .film: return "film.playback.v1"
        }
    }

