import Foundation
import CryptoKit
import MeowSQLite

public enum SQLiteDatabaseRole: String, Sendable, Equatable {
    case data
    case cache

    public var fileName: String {
        switch self {
        case .data: return "meowfilm-data.sqlite3"
        case .cache: return "meowfilm-cache.sqlite3"
        }
    }

    public var applicationID: Int {
        switch self {
        case .data: return SQLiteSchema.dataApplicationID
        case .cache: return SQLiteSchema.cacheApplicationID
        }
    }

    public var synchronousSQL: String {
        switch self {
        case .data: return "FULL"
        case .cache: return "NORMAL"
        }
    }

    var schemaResourceName: String {
        switch self {
        case .data: return "storage-data-schema"
        case .cache: return "storage-cache-schema"
        }
    }
}

/// Authoritative iOS SQLite schema definition loaded from the bundled
/// `storage-data-schema.sql` / `storage-cache-schema.sql` mirrors generated by `scripts/storage/generate-schema.py`.
public enum SQLiteSchema {
    public static let dataApplicationID = 1_296_450_626   // 0x4D464442 ("MFDB")
    public static let cacheApplicationID = 1_296_450_376  // 0x4D464348 ("MFCH")
    public static let version = 1

    struct Definition: Sendable {
        let role: SQLiteDatabaseRole
        let sql: String
        let hash: String
    }

    static func load(role: SQLiteDatabaseRole) throws -> Definition {
        guard let schemaURL = Bundle.module.url(forResource: role.schemaResourceName, withExtension: "sql"),
              let schemaBytes = try? Data(contentsOf: schemaURL),
              let sql = String(data: schemaBytes, encoding: .utf8),
              !sql.isEmpty else {
            throw SQLiteStorageError.invalidSchema
        }
        let hash = SHA256.hash(data: schemaBytes).map { String(format: "%02x", $0) }.joined()
        return Definition(role: role, sql: sql, hash: hash)
    }

    private struct SchemaEntry: Equatable {
        let type: String
        let name: String
        let tableName: String
        let sql: String?
    }

    static func verifyStructure(of db: SQLiteConnection, against definition: Definition) throws {
        _ = try db.query("SELECT owner,revision FROM owner_revisions LIMIT 0") { _ in () }
        guard try db.queryOne("SELECT schema_hash FROM storage_identity WHERE singleton=1", map: { try $0.text(0) }) == definition.hash else {
            throw SQLiteStorageError.invalidSchema
        }
        var expectedHandle: OpaquePointer?
        guard sqlite3_open_v2(":memory:", &expectedHandle, SQLITE_OPEN_READWRITE | SQLITE_OPEN_CREATE, nil) == SQLITE_OK,
              let expectedHandle else {
            if let expectedHandle { sqlite3_close_v2(expectedHandle) }
            throw SQLiteStorageError.io
        }
        let expected = SQLiteConnection(expectedHandle, isReadOnly: false)
        defer {
            expected.releaseStatements()
            sqlite3_close_v2(expectedHandle)
        }
        guard sqlite3_exec(expectedHandle, definition.sql, nil, nil, nil) == SQLITE_OK else {
            throw SQLiteStorageError.invalidSchema
        }
        let structureSQL = "SELECT type,name,tbl_name,sql FROM sqlite_schema WHERE name NOT LIKE 'sqlite_%' ORDER BY type,name"
        let actualEntries = try db.query(structureSQL) { c in
            SchemaEntry(type: try c.text(0), name: try c.text(1), tableName: try c.text(2), sql: try c.optionalText(3))
        }
        let expectedEntries = try expected.query(structureSQL) { c in
            SchemaEntry(type: try c.text(0), name: try c.text(1), tableName: try c.text(2), sql: try c.optionalText(3))
        }
        guard actualEntries == expectedEntries else {
            throw SQLiteStorageError.invalidSchema
        }
    }
}
