#!/usr/bin/env python3
"""Reproduce public synthetic Aether test inputs; never touches production inputs."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ffmpeg", required=True)
    args = parser.parse_args()
    tests = Path(__file__).resolve().parent.parent
    native = tests.parent.parent
    fixtures = tests / "Fixtures"
    source = native / "VideoKernel/Tests/VideoKernelTests/Fixtures"
    (fixtures / "HLS").mkdir(parents=True, exist_ok=True)
    commands = []

    def run(*values):
        command = ["-nostdin", "-hide_banner", "-loglevel", "error", "-y", *values]
        subprocess.run([args.ffmpeg, *command], cwd=tests, check=True)
        commands.append(command)

    # The source has two-second closed GOPs. Copy its real H.264/AAC into
    # ordinary MPEG-TS segments; no codec substitution or fake HLS MIME type.
    for name, audio in [("rate-audio-video", True), ("rate-video-only", False)]:
        run("-i", f"../../VideoKernel/Tests/VideoKernelTests/Fixtures/{name}.mp4",
            "-t", "24", "-map", "0:v:0", *(["-map", "0:a:0"] if audio else []),
            "-map_metadata", "-1", "-map_chapters", "-1", "-c", "copy",
            "-fflags", "+bitexact", "-f", "hls", "-hls_time", "4",
            "-hls_list_size", "0", "-hls_playlist_type", "vod",
            "-hls_flags", "independent_segments",
            "-hls_segment_filename", f"Fixtures/HLS/{name}-%03d.ts",
            f"Fixtures/HLS/{name}.m3u8")

    # MPEG-4 Part 2 is enabled by the locked FFmpegBuild and absent from the
    # native codec allowlist. Matroska bitexact mode avoids random segment UIDs.
    run("-i", "../../VideoKernel/Tests/VideoKernelTests/Fixtures/rate-video-only.mp4",
        "-t", "24", "-map", "0:v:0", "-map_metadata", "-1", "-map_chapters", "-1",
        "-vf", "fps=10,scale=96:64", "-c:v", "mpeg4", "-q:v", "5", "-g", "10",
        "-bf", "0", "-threads", "1", "-pix_fmt", "yuv420p",
        "-flags:v", "+bitexact", "-fflags", "+bitexact", "Fixtures/software-mpeg4-video.mkv")

    # Retained FFV1 is an existing fixture, not regenerated by this tool.
    names = [fixtures / "software-video.mkv", fixtures / "software-mpeg4-video.mkv"]
    for stem in ["rate-audio-video", "rate-video-only"]:
        names += [fixtures / "HLS" / f"{stem}-{index:03d}.ts" for index in range(6)]
        names.append(fixtures / "HLS" / f"{stem}.m3u8")
    (fixtures / "manifest.json").write_text(json.dumps({
        "purpose": "public synthetic playback fixtures only; not production dependency evidence",
        "generator": subprocess.check_output([args.ffmpeg, "-version"], text=True).splitlines()[0],
        "toolSHA256": sha256(Path(args.ffmpeg)),
        "commandWorkingDirectory": "native/AetherKernel/Tests",
        "commands": commands,
        "inputs": {f"native/VideoKernel/Tests/VideoKernelTests/Fixtures/{name}.mp4":
                   sha256(source / f"{name}.mp4")
                   for name in ["rate-audio-video", "rate-video-only"]},
        "retained": ["software-video.mkv"],
        "sha256": {str(path.relative_to(fixtures)): sha256(path) for path in names}
    }, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
